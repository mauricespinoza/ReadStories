#!/usr/bin/env python3
"""Build data/stories.js and data/dictionary.js from the plain-text sources.

Usage:  python3 tools/build.py            # build
        python3 tools/build.py --missing  # also list words without dictionary entry

Sources:
  content/stories.txt     stories (see header of that file for the format)
  content/dictionary.txt  word | pronunciation | meaning in Spanish
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORD_RE = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)*")


def parse_stories(path):
    stories, cur, in_text, para = [], None, False, []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if line.startswith("#") and not in_text:
            continue
        if line.startswith("=== "):
            if cur:
                if para:
                    cur["paragraphs"].append(para)
                stories.append(cur)
            cur, in_text, para = {"id": line[4:].strip(), "paragraphs": []}, False, []
            continue
        if cur is None:
            continue
        if not in_text:
            if line.strip() == "---":
                in_text = True
            elif ":" in line:
                k, v = line.split(":", 1)
                cur[k.strip()] = v.strip()
            continue
        if not line.strip():
            if para:
                cur["paragraphs"].append(para)
                para = []
            continue
        if "||" not in line:
            sys.exit(f"[{cur['id']}] missing '||' in line: {line}")
        en, es = (s.strip() for s in line.split("||", 1))
        para.append([en, es])
    if cur:
        if para:
            cur["paragraphs"].append(para)
        stories.append(cur)
    for s in stories:
        s["tags"] = [t.strip() for t in s.get("tags", "").split(",") if t.strip()]
        s["level"] = int(s.get("level", 1))
        s["words"] = sum(len(WORD_RE.findall(en)) for p in s["paragraphs"] for en, _ in p)
    return stories


def parse_dict(path):
    d = {}
    if not path.exists():
        return d
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not raw.strip() or raw.startswith("#"):
            continue
        parts = raw.split("|")
        if len(parts) < 3:
            sys.exit(f"dictionary.txt line {n}: expected 'word | pronunciation | meaning': {raw!r}")
        w = parts[0].strip().lower()
        if w in d:
            print(f"  note: duplicate entry '{w}' (line {n}) — keeping the last one")
        d[w] = [parts[1].strip(), parts[2].strip()]
    return d


def main():
    stories = parse_stories(ROOT / "content" / "stories.txt")
    dic = parse_dict(ROOT / "content" / "dictionary.txt")
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "stories.js").write_text(
        "// Generated by tools/build.py — edit content/stories.txt instead.\n"
        "window.STORIES = " + json.dumps(stories, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8")
    (ROOT / "data" / "dictionary.js").write_text(
        "// Generated by tools/build.py — edit content/dictionary.txt instead.\n"
        "// word: [pronunciación simple, significado]\n"
        "window.DICT = " + json.dumps(dic, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8")

    words = {}
    for s in stories:
        for w in WORD_RE.findall(s["title"].replace("’", "'")):
            words.setdefault(w.lower(), set()).add(s["id"])
        for p in s["paragraphs"]:
            for en, _ in p:
                for w in WORD_RE.findall(en.replace("’", "'")):
                    words.setdefault(w.lower(), set()).add(s["id"])
    missing = sorted(w for w in words if w not in dic and not (w.endswith("'s") and w[:-2] in dic))
    print(f"{len(stories)} stories, {len(words)} unique words, {len(dic)} dictionary entries, "
          f"{len(missing)} missing")
    if "--missing" in sys.argv:
        print("\n".join(missing))


if __name__ == "__main__":
    main()
